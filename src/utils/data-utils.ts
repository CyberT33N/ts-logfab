import type { ReadonlyDeep, WritableDeep } from 'type-fest'

/**
 * Deeply clones a readonly object and returns a mutable version of it.
 * Use this when API boundaries require mutation of originally immutable structures.
 */
export function toWritable<T>(data: ReadonlyDeep<T>): WritableDeep<T> {
    return structuredClone(data) as WritableDeep<T>
}